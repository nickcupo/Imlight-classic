    public void Dispose() => ClassicRuntime.ResetForTests();

    private static string Overlay(string kind, string name)
        => Path.Combine(ClassicDataFixture.Root, "spiraldb-overlay", kind, name + ".json");

    private static QuestTemplate LoadQuest(string name)
        => JsonConvert.DeserializeObject<QuestTemplate>(File.ReadAllText(Overlay("QuestTemplates", name)), s_json)!;

    private static Wizard WizardOf(MagicSchool school, int level) => new() {
        CharId = 1,
        Zone = "WizardCity/WC_Streets/WC_OldeTown",
        MagicSchoolBehavior = new ServerMagicSchoolBehavior { Level = level, MagicSchool = school },
        QuestBehavior = new ServerQuestBehavior(),
    };

    private static bool Meets(QuestTemplate quest, Wizard wizard)
        => RequirementDispatcher.EvaluateRequirements(quest.m_requirements,
            new QuestRequirementContext(quest.m_requirements, null, null, wizard, quest.m_questName));

    private static bool Passes(RequirementList requirements, Wizard wizard)
        => requirements is null || RequirementDispatcher.EvaluateRequirements(requirements,
            new QuestRequirementContext(requirements, null, null, wizard, null));

    private static void Complete(Wizard wizard, params string[] quests) {
        foreach (var quest in quests) {
            Assert.True(wizard.QuestBehavior.SetQuestRegistryValue(quest, "Complete", 1));
        }
    }

    private static List<ResLearnSpell> Learned(QuestTemplate quest, Wizard wizard)
        => quest.m_endResults.m_results.OfType<ResLearnSpell>().Where(r => Passes(r.m_requirements, wizard)).ToList();

    [Fact]
    public void TheSpellChainOpensAtLevels35And55InTheNotesOrder() {
        var guy = LoadQuest(IKnowAGuy);
        var thief = LoadQuest(ThiefOfSpells);
        var trade = LoadQuest(SpellTrade);
        var runedown = LoadQuest(Runedown);

        var low = WizardOf(MagicSchool.Fire, 34);
        Complete(low, OneInTheSnout);
        Assert.False(Meets(guy, low));
        var wizard = WizardOf(MagicSchool.Fire, 35);
        Assert.False(Meets(guy, wizard));   // One in the Snout first
        Complete(wizard, OneInTheSnout);
        Assert.True(Meets(guy, wizard));
        Assert.False(Meets(thief, wizard));
        Complete(wizard, IKnowAGuy);
        Assert.True(Meets(thief, wizard));

        Complete(wizard, ThiefOfSpells, SuSuSudrilund);
        Assert.False(Meets(trade, wizard));   // level 55
        var high = WizardOf(MagicSchool.Fire, 55);
        Complete(high, ThiefOfSpells);
        Assert.False(Meets(trade, high));   // Su Su Sudrilund too
        Complete(high, SuSuSudrilund);
        Assert.True(Meets(trade, high));
        Assert.False(Meets(runedown, high));
        Complete(high, SpellTrade);
        Assert.True(Meets(runedown, high));
    }

    [Fact]
    public void EachErikQuestTeachesEverySchoolOnlyItsOwnCards() {
        foreach (var (name, balanceCards) in new[] { (ThiefOfSpells, 2), (Runedown, 1) }) {
            var quest = LoadQuest(name);
            var all = quest.m_endResults.m_results.OfType<ResLearnSpell>().ToList();
            Assert.Equal(6 + balanceCards, all.Count);
            Assert.All(all, r => Assert.NotEqual(0u, r.m_templateID));
            Assert.Equal(all.Count, all.Select(r => r.m_templateID).Distinct().Count());
            var taught = new HashSet<uint>();
            foreach (var school in Schools) {
                var mine = Learned(quest, WizardOf(school, 60));
                Assert.Equal(school == MagicSchool.Balance ? balanceCards : 1, mine.Count);
                Assert.All(mine, r => Assert.True(taught.Add(r.m_templateID), $"{name}: a card taught to two schools"));
            }

            Assert.Equal(all.Count, taught.Count);
        }

        // the two quests teach different cards
        Assert.Empty(LoadQuest(ThiefOfSpells).m_endResults.m_results.OfType<ResLearnSpell>().Select(r => r.m_templateID)
            .Intersect(LoadQuest(Runedown).m_endResults.m_results.OfType<ResLearnSpell>().Select(r => r.m_templateID)));
    }

    [Fact]
    public void ThePetQuestsOpenOnlyForTheirSchoolAtLevel58AfterTheLevel48QuestAndNordrilundExposure() {
        foreach (var school in Schools) {
            var (professor, level48, egg, _) = Pets[school];
            var offer = LoadQuest(professor);
            var eggQuest = LoadQuest(egg);

            var wizard = WizardOf(school, 58);
            Assert.False(Meets(offer, wizard), $"{professor} open with nothing done");
            Complete(wizard, level48);
            Assert.False(Meets(offer, wizard), $"{professor} open before Nordrilund Exposure");
            Complete(wizard, NordrilundExposure);
            Assert.True(Meets(offer, wizard), $"{professor} not open");

            var young = WizardOf(school, 57);
            Complete(young, level48, NordrilundExposure);
            Assert.False(Meets(offer, young), $"{professor} open below level 58");

            var other = WizardOf(school == MagicSchool.Fire ? MagicSchool.Ice : MagicSchool.Fire, 58);
            Complete(other, level48, NordrilundExposure);
            Assert.False(Meets(offer, other), $"{professor} open for another school");

            Assert.False(Meets(eggQuest, wizard), $"{egg} open before {professor}");
            Complete(wizard, professor);
            Assert.True(Meets(eggQuest, wizard), $"{egg} not open after {professor}");
        }
    }

    [Fact]
    public void EachEggQuestRewardsItsSchoolsPet() {
        var pets = new HashSet<string>();
        foreach (var school in Schools) {
            var (_, _, egg, pet) = Pets[school];
            var table = JObject.Parse(File.ReadAllText(Overlay("DropTables", egg)));
            var item = Assert.Single((JArray) table["Items"]!);
            Assert.Equal(pet, (string?) item["ItemId"]);
            Assert.Equal(school.ToString(), (string?) item["Requirements"]!["m_requirements"]![0]!["m_magicSchool"]);
            Assert.True((int) table["ExperienceAmount"]! > 0);
            Assert.True(pets.Add(pet));
        }
    }

    [Fact]
    public void OlderProfilesServeNoneOfThem() {
        var names = new[] { IKnowAGuy, ThiefOfSpells, SpellTrade, Runedown }
            .Concat(Pets.Values.SelectMany(p => new[] { p.Professor, p.Egg })).ToList();
        var lines = File.ReadAllLines(Path.Combine(ClassicDataFixture.Root, "spiraldb-overlay", "QuestTemplates", "_disabled.txt"));
        ConcurrentDictionary<string, QuestTemplate> Loaded()
            => new(names.ToDictionary(n => n, n => new QuestTemplate { m_questName = n }), StringComparer.OrdinalIgnoreCase);

        foreach (var older in new[] { "celestia-2010", "october-2010-arc1", "late-2009", "arc1-2009h1" }) {
            var quests = Loaded();
            SpiralDB.ApplyTombstoneLines(lines, quests, SpiralDB.RestoredQuests(ClassicDataFixture.LoadProfile(older)));
            Assert.Empty(quests);
        }

        var mine = Loaded();
        SpiralDB.ApplyTombstoneLines(lines, mine, SpiralDB.RestoredQuests(ClassicDataFixture.LoadProfile(Wintertusk)));
        Assert.Equal(names.Count, mine.Count);
    }

}
