    private const string IKnowAGuy = "WC-SPELL-C01-001";
    private const string ThiefOfSpells = "GH-SPELL-C01-001";
    private const string SpellTrade = "WC-SPELL-C02-001";
    private const string Runedown = "GH-SPELL-C02-001";
    private const string OneInTheSnout = "GH-WOLF-C01-001";
    private const string SuSuSudrilund = "GH-FJORD-C05-003";
    private const string NordrilundExposure = "GH-FJORD-C05-004";

    private static readonly MagicSchool[] Schools =
        [MagicSchool.Fire, MagicSchool.Ice, MagicSchool.Storm, MagicSchool.Myth, MagicSchool.Life, MagicSchool.Death, MagicSchool.Balance];

    /// <summary>school -> (professor quest, its level 48 prerequisite, egg quest, pet template)</summary>
    private static readonly Dictionary<MagicSchool, (string Professor, string Level48, string Egg, string Pet)> Pets = new() {
        [MagicSchool.Fire] = ("WC-FIRE-C08-001", "WC-FIRE-C06-003", "GH-FIRE-C09-001", "446100"),
        [MagicSchool.Ice] = ("WC-ICE-C08-001", "WC-ICE-C06-004", "GH-ICE-C09-001", "446081"),
        [MagicSchool.Storm] = ("WC-STORM-C08-001", "WC-STRM-C06-004", "GH-STORM-C09-001", "446085"),
        [MagicSchool.Myth] = ("WC-MYTH-C08-001", "WC-MYTH-C06-004", "GH-MYTH-C09-001", "446097"),
        [MagicSchool.Life] = ("WC-LIFE-C08-001", "WC-LIFE-C06-004", "GH-LIFE-C09-001", "446089"),
        [MagicSchool.Death] = ("WC-DEATH-C08-001", "WC-DETH-C06-004", "GH-DEATH-C09-001", "446093"),
        [MagicSchool.Balance] = ("KT-BAL-C08-001", "KT-BAL-C06-004", "GH-BAL-C09-001", "446096"),
    };

    private static readonly JsonSerializerSettings s_json = new() {
        TypeNameHandling = TypeNameHandling.Auto,
        NullValueHandling = NullValueHandling.Ignore,
    };

    public WintertuskSpellPetQuestTests() {
